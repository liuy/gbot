// RegisterArtifactRoutes mounts the artifact HTTP surface for dir (the
// projectspace artifacts directory):
//
//   - GET /artifacts/{name...} serves a single artifact file, falling back to
//     the embedded builtin game page for registry names when nothing is on disk
//   - POST /artifacts/{name...} runs the game observer (observation → LLM move)
//     for registry names only
//   - GET /api/artifacts lists the directory (name, size, mtime; newest first)
//   - DELETE /api/artifacts removes every artifact file, keeping the directory
//
// Registered patterns are more specific than the SPA catch-all "/", so they
// win during mux matching.
func RegisterArtifactRoutes(mux *http.ServeMux, dir string, observe ObserveProviderFn) {
	mux.HandleFunc("GET /artifacts/{name...}", func(w http.ResponseWriter, r *http.Request) {
		name := r.PathValue("name")
		full, status := artifactFilePath(dir, name)
		if status != 0 {
			http.Error(w, http.StatusText(status), status)
			return
		}
		// allow-same-origin: the document shares the wui origin, so
		// localStorage/fullscreen/dialogs work (the user explicitly trusts
		// artifact content — all of it is generated by this agent).
		// Cross-origin resources stay blocked by default-src; the blast
		// radius of an injected page is capped at this origin.
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Security-Policy", "default-src 'self' 'unsafe-inline' data:; sandbox allow-scripts allow-same-origin")
		w.Header().Set("X-Frame-Options", "SAMEORIGIN")

		f, err := os.Open(full)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			http.Error(w, "not found", http.StatusNotFound)
			return
		}
		if err == nil {
			defer f.Close()
			st, stErr := f.Stat()
			if stErr != nil {
				// Only "missing" or a directory falls through to the bundled
				// fallback; an unexplainable stat failure is a plain 404.
				http.Error(w, "not found", http.StatusNotFound)
				return
			}
			if !st.IsDir() {
				// Zero modtime: ServeContent emits no Last-Modified and never
				// negotiates a 304 — combined with no-store this guarantees an
				// iframe reload always fetches fresh content.
				http.ServeContent(w, r, st.Name(), time.Time{}, f)
				return
			}
		}
		// Missing on disk (or a bare directory): serve the embedded builtin
		// game page for registry names. Same headers as the file path, so the
		// sheet iframe behaves identically either way.
		if serveBundledGame(w, r, name) {
			return
		}
		http.Error(w, "not found", http.StatusNotFound)
	})

	mux.HandleFunc("POST /artifacts/{name...}", observerHandler(observe))

	mux.HandleFunc("GET /api/artifacts", func(w http.ResponseWriter, r *http.Request) {
		items, status := listArtifacts(dir)
		if status != 0 {
			http.Error(w, http.StatusText(status), status)
			return
		}
		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Content-Type", "application/json")
		payload, _ := json.Marshal(items)
		_, _ = w.Write(payload)
	})

	mux.HandleFunc("DELETE /api/artifacts", func(w http.ResponseWriter, r *http.Request) {
		if status := clearArtifacts(dir); status != 0 {
			http.Error(w, http.StatusText(status), status)
			return
		}
		w.WriteHeader(http.StatusNoContent)
	})
}

// serveBundledGame serves the embedded page for a builtin registry name and
// reports whether the name is registered.
func serveBundledGame(w http.ResponseWriter, r *http.Request, name string) bool {
	if _, known := builtinGames[name]; !known {
		return false
	}
	http.ServeContent(w, r, "chess.html", time.Time{}, bytes.NewReader(chessTemplate))
	return true
}

// artifactListItem is one entry of the /api/artifacts listing. Mtime is unix
// milliseconds to match session_list's updatedAt (both feed the frontend's
// relative-time formatter).
type artifactListItem struct {
	Name  string `json:"name"`
	Size  int64  `json:"size"`
	Mtime int64  `json:"mtime"`
}

// listArtifacts walks dir collecting regular files as slash-separated
// relative names, newest first. The walk is recursive because artifact names
// may contain directories (the serve route's {name...} matches them). A
// missing dir is the normal pre-first-write state and lists as empty; any
// other walk failure surfaces as 500.
func listArtifacts(dir string) ([]artifactListItem, int) {
	items := []artifactListItem{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		items = append(items, artifactListItem{
			Name:  filepath.ToSlash(rel),
			Size:  info.Size(),
			Mtime: info.ModTime().UnixMilli(),
		})
		return nil
	})
	if err != nil {
		if os.IsNotExist(err) {
			return []artifactListItem{}, 0
		}
		return nil, http.StatusInternalServerError
	}
	sort.SliceStable(items, func(i, j int) bool { return items[i].Mtime > items[j].Mtime })
	return items, 0
}

// clearArtifacts removes every regular file under dir, keeping the directory
// itself (and any nested directories, even once empty — listArtifacts only
// ever reports files, so the leftover dirs stay invisible). A missing dir is
// the nothing-to-clear case and reports 0; any other walk failure surfaces as
// 500. Per-file remove errors abort the walk so a failing delete is visible
// instead of silently half-done.
func clearArtifacts(dir string) int {
	// Stat first: a missing dir is the nothing-to-clear case. Without this,
	// ENOENT from the walk gets conflated with ENOENT from a file that
	// vanished mid-walk, silently leaving later files undeleted.
	if _, err := os.Stat(dir); err != nil {
		if os.IsNotExist(err) {
			return 0
		}
		return http.StatusInternalServerError
	}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		// A file that vanished mid-walk is already deleted — keep going so
		// one race doesn't strand the rest of the directory.
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		return nil
	})
	if err != nil {
		return http.StatusInternalServerError
	}
	return 0
}

// artifactFilePath resolves an artifact name under dir. PathValue is
// already percent-decoded, which is why encoded traversal (%2e%2e%2f) is
// caught by the same ".." segment check as its literal form. The prefix
// re-check after Join is belt-and-braces against any name that cleans to
// dir itself or escapes it.
func artifactFilePath(dir, name string) (string, int) {
	if name == "" {
		return "", http.StatusBadRequest
	}
	for _, seg := range strings.Split(name, "/") {
		if seg == ".." {
			return "", http.StatusBadRequest
		}
	}
	full := filepath.Join(dir, filepath.FromSlash(name))
	if !strings.HasPrefix(full, dir+string(os.PathSeparator)) {
		return "", http.StatusBadRequest
	}
	return full, 0
}
