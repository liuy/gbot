// CacheControlConfig carries cache control settings for Anthropic API.
// Source: claude.ts:358-374
type CacheControlConfig struct {
	Type  string `json:"type"`            // "ephemeral"
	TTL   string `json:"ttl,omitempty"`   // "1h", "5m", etc.
	Scope string `json:"scope,omitempty"` // "global" | "org" | "" (none)
}

// ContentBlock is a discriminated union for message content.
// Source: Anthropic API content block types.
type ContentBlock struct {
	Type ContentType `json:"type"`

	// Text content (type == "text")
	Text string `json:"text,omitempty"`

	// Thinking content (type == "thinking")
	// Anthropic API requires "thinking" field (not "text") for thinking blocks.
	Thinking string `json:"thinking,omitempty"`
	// Signature is the Anthropic-issued opaque signature for thinking blocks.
	// Must be replayed verbatim; the API rejects modified signatures.
	// TS parity: claude.ts initializes signature: '' at content_block_start;
	// Go's zero value for string is automatic, so we rely on omitempty on send.
	Signature string `json:"signature,omitempty"`
	// ThinkingDurationNs records wall-clock thinking time in nanoseconds.
	// Set on thinking_end; not part of Anthropic API schema, not persisted.
	ThinkingDurationNs int64 `json:"-"`

	// Tool use fields (type == "tool_use")
	ID    string          `json:"id,omitempty"`
	Name  string          `json:"name,omitempty"`
	Input json.RawMessage `json:"input,omitempty"`

	// Tool result fields (type == "tool_result")
	ToolUseID string          `json:"tool_use_id,omitempty"`
	Content   json.RawMessage `json:"content,omitempty"`
	IsError   bool            `json:"is_error,omitempty"`

	// Redacted thinking data (type == "redacted_thinking")
	// Must be preserved verbatim and replayed to the API.
	Data string `json:"data,omitempty"`

	// Image content (type == "image")
	// Source: Anthropic API image content block — {type:"image", source:{type:"base64", media_type, data}}.
	Source *ImageSource `json:"source,omitempty"`

	// Cache control for incremental caching on the last block.
	// Source: claude.ts:3089-3106 — addCacheBreakpoints adds cache_control
	// only to the last block of the last message.
	CacheControl *CacheControlConfig `json:"cache_control,omitempty"`
}

// NewTextBlock creates a text content block.
func NewTextBlock(text string) ContentBlock {
	return ContentBlock{Type: ContentTypeText, Text: text}
}

// NewToolUseBlock creates a tool_use content block.
func NewToolUseBlock(id, name string, input json.RawMessage) ContentBlock {
	return ContentBlock{Type: ContentTypeToolUse, ID: id, Name: name, Input: input}
}

// NewToolResultBlock creates a tool_result content block.
func NewToolResultBlock(toolUseID string, content json.RawMessage, isError bool) ContentBlock {
	return ContentBlock{
		Type:      ContentTypeToolResult,
		ToolUseID: toolUseID,
		Content:   content,
		IsError:   isError,
	}
}

// ImageSource is the source payload of an image content block.
// Source: Anthropic API image block source — {type:"base64", media_type, data}.
//
// Two source types are supported:
//   - "base64": Data carries inline base64-encoded bytes (the only wire form
//     the Anthropic/OpenAI APIs accept).
//   - "file": Path references a local file that providers read and base64-
//     encode at request time (see llm.MaterializeFileImages). Used by the
//     WeChat connector to avoid storing large base64 blobs in the message DB.
type ImageSource struct {
	Type      string `json:"type"`           // "base64" | "file"
	MediaType string `json:"media_type"`     // "image/png", "image/jpeg", etc.
	Data      string `json:"data,omitempty"` // base64-encoded bytes (Type == "base64")
	Path      string `json:"path,omitempty"` // local file path (Type == "file")
}

// IsFileSource returns true if the source references a local file that must be
// read and base64-encoded at request time (Type == "file").
func (s *ImageSource) IsFileSource() bool { return s != nil && s.Type == "file" }

// NewImageBlock creates an image content block carrying base64-encoded image data.
func NewImageBlock(source ImageSource) ContentBlock {
	return ContentBlock{Type: ContentTypeImage, Source: &source}
}

// NewFileImageBlock creates an image content block referencing a local file.
// The provider reads and base64-encodes Path at request time (see
// llm.MaterializeFileImages). mediaType must be an image/* MIME type.
func NewFileImageBlock(mediaType, path string) ContentBlock {
	return ContentBlock{
		Type:   ContentTypeImage,
		Source: &ImageSource{Type: "file", MediaType: mediaType, Path: path},
	}
}

