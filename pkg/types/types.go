// Role represents the role of a message sender.
type Role string

const (
	RoleUser      Role = "user"
	RoleAssistant Role = "assistant"
	RoleSystem    Role = "system"
)

// Message represents a single message in the conversation.
// Source: Anthropic API Message type + internal message extensions.
type Message struct {
	ID          string         `json:"id,omitempty"`
	Role        Role           `json:"role"`
	Content     []ContentBlock `json:"content"`
	Model       string         `json:"model,omitempty"`
	StopReason  string         `json:"stop_reason,omitempty"`
	Usage       *Usage         `json:"usage,omitempty"`
	Timestamp   time.Time      `json:"timestamp"`
	Flags       MessageFlag    `json:"flags,omitempty"`
	MessageType MessageType    `json:"message_type,omitempty"`
	Attachment  *Attachment    `json:"attachment,omitempty"`
}

// MessageFlag is a bitmask for message metadata flags.
// Source: TS message flags (isCompactSummary, isMeta, isVisibleInTranscriptOnly).
type MessageFlag uint

const (
	// FlagCompactSummary marks messages generated by the compact system
	// (boundary markers and conversation summaries).
	// Source: TS isCompactSummary in MessageSelector.tsx:780.
	FlagCompactSummary MessageFlag = 1 << iota

	// FlagMeta marks system-generated messages hidden from the UI.
	// Source: TS isMeta in MessageSelector.tsx:777.
	FlagMeta

	// FlagVisibleInTranscriptOnly marks messages visible only in transcript view.
	// Source: TS isVisibleInTranscriptOnly in MessageSelector.tsx:780.
	FlagVisibleInTranscriptOnly
)

// HasFlag checks if the message has a specific flag set.
func (m *Message) HasFlag(flag MessageFlag) bool {
	return m.Flags&flag != 0
}

// Usage tracks token consumption.
// Source: Anthropic API Usage type.
type Usage struct {
	InputTokens              int `json:"input_tokens"`                          // new (non-cached) input tokens
	OutputTokens             int `json:"output_tokens"`                         // output tokens
	CacheCreationInputTokens int `json:"cache_creation_input_tokens,omitempty"` // new tokens added to cache
	CacheReadInputTokens     int `json:"cache_read_input_tokens,omitempty"`     // tokens read from cache
}

// TotalInputTokens returns the total billed input tokens (new + cache read + cache create).
// Source: minimax cache docs — total = input + cache_read + cache_creation.
func (u Usage) TotalInputTokens() int {
	return u.InputTokens + u.CacheReadInputTokens + u.CacheCreationInputTokens
}

// SetMetadataFromJSON restores Usage/Model/StopReason/Flags/MessageType/Attachment from a JSON metadata string.
// Used by storage layer to deserialize the metadata column back into message fields.
func (m *Message) SetMetadataFromJSON(metadata string) {
	if metadata == "" {
		return
	}
	var meta struct {
		Usage       *Usage      `json:"usage,omitempty"`
		Model       string      `json:"model,omitempty"`
		StopReason  string      `json:"stop_reason,omitempty"`
		Flags       MessageFlag `json:"flags,omitempty"`
		MessageType MessageType `json:"message_type,omitempty"`
		Attachment  *Attachment `json:"attachment,omitempty"`
	}
	if err := json.Unmarshal([]byte(metadata), &meta); err == nil {
		m.Usage = meta.Usage
		m.Model = meta.Model
		m.StopReason = meta.StopReason
		m.Flags = meta.Flags
		m.MessageType = meta.MessageType
		m.Attachment = meta.Attachment
	}
}

// MetadataToJSON serializes Usage/Model/StopReason/Flags/MessageType/Attachment to a JSON metadata string.
// Returns empty string if no metadata fields are set.
func (m *Message) MetadataToJSON() string {
	if m.Usage == nil && m.Model == "" && m.StopReason == "" && m.Flags == 0 && m.MessageType == "" && m.Attachment == nil {
		return ""
	}
	meta := struct {
		Usage       *Usage      `json:"usage,omitempty"`
		Model       string      `json:"model,omitempty"`
		StopReason  string      `json:"stop_reason,omitempty"`
		Flags       MessageFlag `json:"flags,omitempty"`
		MessageType MessageType `json:"message_type,omitempty"`
		Attachment  *Attachment `json:"attachment,omitempty"`
	}{
		Usage:       m.Usage,
		Model:       m.Model,
		StopReason:  m.StopReason,
		Flags:       m.Flags,
		MessageType: m.MessageType,
		Attachment:  m.Attachment,
	}
	if b, err := json.Marshal(meta); err == nil {
		return string(b)
	}
	return ""
}

